type LanguageContextValue = {
  language: AppLanguage
  setLanguage: (language: AppLanguage) => void
  t: (frenchText: string) => string
}

const LanguageContext = createContext<LanguageContextValue | null>(null)

function loadLanguage(): AppLanguage {
  try {
    const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY)
    return saved === 'en' || saved === 'es' ? saved : 'fr'
  } catch {
    return 'fr'
  }
}

export function LanguageProvider({ children }: { children: ReactNode }): React.JSX.Element {
  const [language, setCurrentLanguage] = useState<AppLanguage>(loadLanguage)
  useEffect(() => {
    document.documentElement.lang = language
  }, [language])

  const setLanguage = (nextLanguage: AppLanguage): void => {
    setCurrentLanguage(nextLanguage)
    try {
      localStorage.setItem(LANGUAGE_STORAGE_KEY, nextLanguage)
    } catch {
      // Le choix reste actif jusqu'à la fermeture de l'application.
    }
  }
  const t = (frenchText: string): string =>
    language === 'fr' ? frenchText : (translations[language][frenchText] ?? frenchText)

  return <LanguageContext.Provider value={{ language, setLanguage, t }}>{children}</LanguageContext.Provider>
}

export function useLanguage(): LanguageContextValue {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useLanguage must be used inside LanguageProvider')
  return context
}
